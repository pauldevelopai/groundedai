// AI-crawler policy — newsroom-level allow/disallow rules for the major
// AI training crawlers, rendered to robots.txt / ai.txt / llms.txt snippets
// the newsroom can paste at the root of their public site.
//
// The platform itself does NOT enforce these rules anywhere — they're an
// advisory the newsroom publishes externally. The Archive workspace exposes
// the editor + snippet downloads; the rest of the platform is unaware.
//
// Data shape (newsroom_profile.metadata.ai_crawler_policy):
//   {
//     bots: { GPTBot: true|false, ClaudeBot: true|false, ... },
//     default_allow: true|false,                  // policy for any unlisted bot
//     disallow_paths: ['/investigations/', '/exclusive/']
//   }
//
// Defaults below disallow the major LLM training crawlers — the assumption
// most African newsrooms in the pilot will want their archive protected
// from free corporate training scrape. They can flip individual toggles to
// allow if they prefer.

const { pool } = require('../db');
const { mergeWithOverrides } = require('./merge-overrides');

// The bots Grounded knows about. Add new ones here as they appear in the
// wild — the UI iterates this list. Order is what the editor renders.
const KNOWN_BOTS = [
  { name: 'GPTBot', label: 'OpenAI GPTBot', purpose: 'Training ChatGPT / GPT models' },
  { name: 'ChatGPT-User', label: 'OpenAI ChatGPT-User', purpose: 'Live browsing inside ChatGPT' },
  { name: 'OAI-SearchBot', label: 'OpenAI SearchBot', purpose: 'OpenAI search index' },
  { name: 'ClaudeBot', label: 'Anthropic ClaudeBot', purpose: 'Training Claude models' },
  { name: 'Claude-Web', label: 'Anthropic Claude-Web', purpose: 'Live browsing inside Claude' },
  { name: 'anthropic-ai', label: 'Anthropic (legacy)', purpose: 'Anthropic legacy training crawler' },
  { name: 'Google-Extended', label: 'Google-Extended', purpose: 'Training Gemini / Bard (separate from Googlebot)' },
  { name: 'PerplexityBot', label: 'PerplexityBot', purpose: 'Perplexity AI answer engine' },
  { name: 'CCBot', label: 'Common Crawl (CCBot)', purpose: 'Common Crawl — feeds most public LLM training sets' },
  { name: 'Bytespider', label: 'ByteDance Bytespider', purpose: 'ByteDance / TikTok AI training' },
  { name: 'Amazonbot', label: 'Amazonbot', purpose: 'Amazon AI (Alexa, AWS LLMs)' },
  { name: 'FacebookBot', label: 'Meta FacebookBot', purpose: 'Meta AI / LLaMA training' },
  { name: 'Applebot-Extended', label: 'Apple Applebot-Extended', purpose: 'Apple Intelligence (separate from Applebot)' },
  { name: 'cohere-ai', label: 'Cohere', purpose: 'Cohere AI training' },
  { name: 'Diffbot', label: 'Diffbot', purpose: 'Commercial knowledge-graph crawler' },
];

// Default policy: disallow all known LLM training bots. Newsrooms override
// per-bot. "default_allow: false" means unknown future bots are also blocked
// (newsroom can flip).
const DEFAULT_POLICY = {
  bots: Object.fromEntries(KNOWN_BOTS.map((b) => [b.name, false])),
  default_allow: false,
  disallow_paths: [],
};

async function getEffectiveAiCrawlerPolicy(newsroomId) {
  if (!newsroomId) return cloneDefault();
  const { rows } = await pool.query(
    `SELECT metadata->'ai_crawler_policy' AS override FROM newsroom_profiles WHERE newsroom_id = $1`,
    [newsroomId]
  );
  const override = rows[0]?.override;
  if (!override) return cloneDefault();
  return mergeWithOverrides(cloneDefault(), override);
}

function cloneDefault() {
  return {
    bots: { ...DEFAULT_POLICY.bots },
    default_allow: DEFAULT_POLICY.default_allow,
    disallow_paths: [...DEFAULT_POLICY.disallow_paths],
  };
}

// ─── Snippet rendering ─────────────────────────────────────────────────────

/**
 * Render a robots.txt fragment encoding the policy. Newsrooms append this
 * to (or replace) their existing robots.txt at the site root.
 */
function renderRobotsTxt(policy) {
  const lines = [];
  lines.push('# AI crawler policy — generated by Grounded');
  lines.push('# https://grounded.example  (replace with your platform URL)');
  lines.push('');

  for (const bot of KNOWN_BOTS) {
    const allow = policy.bots?.[bot.name] ?? policy.default_allow;
    lines.push(`# ${bot.label} — ${bot.purpose}`);
    lines.push(`User-agent: ${bot.name}`);
    if (allow) {
      lines.push('Allow: /');
      for (const p of policy.disallow_paths || []) lines.push(`Disallow: ${p}`);
    } else {
      lines.push('Disallow: /');
    }
    lines.push('');
  }

  // Catch-all for any bot the platform doesn't enumerate.
  lines.push('# All other crawlers (catch-all)');
  lines.push('User-agent: *');
  if (policy.default_allow) {
    if ((policy.disallow_paths || []).length > 0) {
      for (const p of policy.disallow_paths) lines.push(`Disallow: ${p}`);
    } else {
      lines.push('Allow: /');
    }
  } else {
    lines.push('# (Catch-all unspecified — your existing robots.txt rules apply.)');
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Render an ai.txt fragment — the emerging convention published by
 * Spawning.ai et al. Same payload, different format. We emit the simple
 * key:value flavour many crawlers respect.
 */
function renderAiTxt(policy) {
  const lines = [];
  lines.push('# ai.txt — AI-training crawler policy');
  lines.push('# Generated by Grounded. See https://site.spawning.ai/spawning-ai-txt');
  lines.push('');
  lines.push(`User-Agent: *`);
  lines.push(`Disallow-AI-Training: ${policy.default_allow ? 'allow' : 'disallow'}`);
  if ((policy.disallow_paths || []).length > 0) {
    for (const p of policy.disallow_paths) lines.push(`Disallow: ${p}`);
  }
  lines.push('');
  for (const bot of KNOWN_BOTS) {
    const allow = policy.bots?.[bot.name] ?? policy.default_allow;
    lines.push(`User-Agent: ${bot.name}`);
    lines.push(`Disallow-AI-Training: ${allow ? 'allow' : 'disallow'}`);
    lines.push('');
  }
  return lines.join('\n');
}

/**
 * Render an llms.txt fragment — the emerging "guide LLMs to your good
 * content" convention. This one is *positive* (we tell crawlers what's
 * worth reading); we keep it minimal.
 */
function renderLlmsTxt(policy, opts = {}) {
  const siteName = opts.siteName || 'Newsroom';
  const lines = [];
  lines.push(`# ${siteName}`);
  lines.push('');
  lines.push('Newsroom archive — please respect our AI-crawler policy in robots.txt and ai.txt.');
  lines.push('');
  if (policy.default_allow) {
    lines.push('AI crawlers: see /robots.txt and /ai.txt for per-bot rules.');
  } else {
    lines.push('AI crawlers: by default our archive is **not** licensed for AI training. See /robots.txt and /ai.txt.');
  }
  lines.push('');
  return lines.join('\n');
}

module.exports = {
  KNOWN_BOTS,
  DEFAULT_POLICY,
  getEffectiveAiCrawlerPolicy,
  renderRobotsTxt,
  renderAiTxt,
  renderLlmsTxt,
};
